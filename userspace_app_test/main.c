void get_char_array(uint8_t c,FONT_SIZE font_size,character_info *ch_str)
{
    uint8_t *p_char;
    uint8_t width;
    uint8_t num_page;

    uint32_t *font_arr;
    uint16_t pos;

    if(c < 32 || c > 125)
    {
        return;
    }
    
    switch (font_size)
    {
        case FONT5X7:
            /* code */
            width = 5;
            num_page = 1;
            font_arr = font5x7;
            break;
        
        case FONT8X12:
            width = 8;
            num_page = 2;
            font_arr = font8x12;
            break;

        case FONT14X24:
            width = 14;
            num_page = 3;
            font_arr = font14x24;
            break;

        case FONT16X32:
            width = 16;
            num_page = 4;
            font_arr = font16x32;
            break;
        default:
            break;
    }

    p_char = (uint8_t*)malloc(sizeof(uint8_t) * width * num_page);
    pos = (c - 32) * width;

    // for (uint8_t i = 0; i < width; i++)
    // {
    //     /* code */
    //     printf("0x%x ",font_arr[pos + i]);
    // }
    // printf("\n");
    // printf("\n");

    for(uint8_t i = 0; i < num_page; i++)
    {
        for (uint8_t j = 0; j < width; j++)
        {
            /* code */
            p_char[i*width + j] = (font_arr[pos + j] >> i*8) & 0xFF;
            //printf("0x%x,",p_char[i*width + j]);
        }
    }
    // printf("\n");
    // printf("\n");
    ch_str->width = width;
    ch_str->num_page = num_page;
    ch_str->start_col = 0;
    ch_str->start_page = 0;
    ch_str->p_character = p_char;
}


